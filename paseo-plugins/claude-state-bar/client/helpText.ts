/**
 * 도움말 풍선("?") 글을 문장마다 줄을 바꾼다(10-24 리규형님 "설명서에 개행 좀" — 풍선 글이 한 덩어리로 보였다). 아무것도 불러오지 않는다(시험이 바로 읽는다).
 * 한국어는 "…다." "…요." 뒤, 영어는 소문자·닫는 괄호 뒤 마침표·물음표·느낌표 다음에 대문자로 시작하는 문장이 올 때, 그리고 번호 목록("… 2. …")의 번호 앞.
 * 번호 자체("1. Open")는 끊지 않는다(숫자 뒤 마침표는 문장 끝으로 보지 않는다). 띄어쓰기만 줄바꿈으로 바꾼다 — 이미 바꾼 줄·빈 줄 문단(\n\n)은 그대로
 */
export function helpLines(text: string): string {
  return text
    .replace(/([다요])\. +(?=\S)/g, "$1.\n")
    .replace(/([.!?)]) +(?=\d{1,2}\. )/g, "$1\n")
    .replace(/([a-z%)\]"'”])([.!?]) +(?=["'“(]?[A-Z])/g, "$1$2\n");
}
